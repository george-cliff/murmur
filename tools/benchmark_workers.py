"""
NUM_WORKERS benchmark for the Sparrowhawk training DataLoader.

Times one full pass over the real fold-0 training set at a few different
worker counts, so NUM_WORKERS in train.py can be set from an actual
measurement instead of a guess. Not part of the training pipeline itself -
run it directly whenever the per-clip data-loading cost changes (e.g.
after adding/changing augmentation) and read the printout.

Run from the repo root: python -m tools.benchmark_workers
(uses an absolute import of the sparrowhawk package, so it can't be run
as a direct script)

Generated by Claude Code.
"""

# stdlib
import time

# third-party
from sklearn.model_selection import train_test_split
from torch.utils.data import DataLoader

# local
from .log import start_logging, write_log
from .paths import TOOLS_LOG_DIR
from sparrowhawk.data import get_manifest, get_fold, filter_manifest, BirdDataset
from sparrowhawk.experiment import (  # stay in sync with the real training run
    BATCH_SIZE,
    AUGMENT_NOISE,
    AUGMENT_MASK,
)

SCOPE = "BENCHMARK"
WORKER_COUNTS_TO_TEST = [4, 6, 8, 10, 12]


if __name__ == "__main__":
    start_logging(TOOLS_LOG_DIR, "benchmark_workers")
    manifest = get_manifest()
    train_names, _ = get_fold(0)
    train_df = filter_manifest(manifest, train_names)
    # mirrors train.py's own fold-0 train/val split, so this benchmarks
    # against the same training set size train.py will actually use
    train_df, _ = train_test_split(
        train_df, test_size=0.15, train_size=0.85, random_state=0
    )

    write_log(
        SCOPE,
        "configured benchmark",
        data_name="train",
        data_rows=len(train_df),
        data_batch_size=BATCH_SIZE,
    )

    for num_workers in WORKER_COUNTS_TO_TEST:
        # augment flags match train.py's real training dataset - noise/masking
        # add real per-clip CPU work (building an rng, copying the array,
        # adding noise or zeroing slices), so benchmarking without them would
        # understate the actual per-clip cost.
        dataset = BirdDataset(
            df=train_df,
            seed=0,
            fold=0,
            augment_noise=AUGMENT_NOISE,
            augment_mask=AUGMENT_MASK,
        )
        dataloader = DataLoader(
            dataset,
            batch_size=BATCH_SIZE,
            shuffle=True,
            num_workers=num_workers,
            pin_memory=True,
        )

        start = time.time()
        for _ in dataloader:
            pass
        elapsed = time.time() - start

        write_log(
            SCOPE,
            "benchmarked worker count",
            data_num_workers=num_workers,
            time_seconds=f"{elapsed:.1f}",
        )
